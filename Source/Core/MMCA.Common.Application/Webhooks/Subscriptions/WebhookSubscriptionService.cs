using Microsoft.Extensions.Options;
using MMCA.Common.Application.Interfaces;
using MMCA.Common.Application.Webhooks.Delivery;
using MMCA.Common.Domain.Webhooks;
using MMCA.Common.Shared.Abstractions;
using MMCA.Common.Shared.Webhooks;

namespace MMCA.Common.Application.Webhooks.Subscriptions;

/// <summary>
/// Default <see cref="IWebhookSubscriptionService"/>. Every call reads and writes the caller's tenant
/// only (<see cref="ITenantContext.TenantId"/>, <see langword="null"/> when there is none); event types
/// must be <c>"*"</c> or registered in the <see cref="WebhookEventCatalog"/>; targets pass the
/// <see cref="IWebhookTargetValidator"/>; and a new secret is generated by
/// <see cref="WebhookSignature.GenerateSecret"/>, stored only protected, and returned once.
/// </summary>
/// <param name="store">Reads and writes the rows.</param>
/// <param name="targetValidator">Refuses non-public targets.</param>
/// <param name="secretProtector">Protects the signing secret at rest.</param>
/// <param name="catalog">The registered webhook event types.</param>
/// <param name="tenantContext">The caller's tenant.</param>
/// <param name="settings">The webhook options.</param>
/// <param name="timeProvider">The clock for disable and rotation instants.</param>
public sealed class WebhookSubscriptionService(
    IWebhookSubscriptionStore store,
    IWebhookTargetValidator targetValidator,
    IWebhookSecretProtector secretProtector,
    WebhookEventCatalog catalog,
    ITenantContext tenantContext,
    IOptions<WebhookSettings> settings,
    TimeProvider timeProvider) : IWebhookSubscriptionService
{
    /// <inheritdoc />
    public bool IsEnabled => settings.Value.Enabled;

    /// <inheritdoc />
    public IReadOnlyCollection<string> EventTypes => catalog.EventTypes;

    private DateTime UtcNow => timeProvider.GetUtcNow().UtcDateTime;

    /// <inheritdoc />
    public async Task<Result<IReadOnlyList<WebhookSubscriptionResponse>>> ListAsync(CancellationToken cancellationToken = default)
    {
        var subscriptions = await store.ListAsync(tenantContext.TenantId, cancellationToken).ConfigureAwait(false);
        IReadOnlyList<WebhookSubscriptionResponse> responses = [.. subscriptions.Select(ToResponse)];
        return Result.Success(responses);
    }

    /// <inheritdoc />
    public async Task<Result<WebhookSubscriptionSecretResponse>> CreateAsync(
        CreateWebhookSubscriptionRequest request,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(request);

        var tenantId = tenantContext.TenantId;

        // A body with no eventTypes member binds null; it is empty, so the domain answers EventTypesRequired.
        var eventTypes = request.EventTypes ?? [];
        var check = CheckDefinition(request.Url, eventTypes, nameof(CreateAsync));
        if (check.IsFailure)
        {
            return Result.Failure<WebhookSubscriptionSecretResponse>(check.Errors);
        }

        var count = await store.CountAsync(tenantId, cancellationToken).ConfigureAwait(false);
        if (count >= settings.Value.MaxSubscriptionsPerTenant)
        {
            return Result.Failure<WebhookSubscriptionSecretResponse>(Error.Conflict(
                WebhookErrorCodes.LimitReached,
                "The tenant already holds the maximum number of webhook subscriptions.",
                nameof(CreateAsync)));
        }

        var target = await ValidateTargetAsync(request.Url, cancellationToken).ConfigureAwait(false);
        if (target.IsFailure)
        {
            return Result.Failure<WebhookSubscriptionSecretResponse>(target.Errors);
        }

        var secret = WebhookSignature.GenerateSecret();
        var created = WebhookSubscription.Create(
            request.Url,
            request.Description,
            [.. eventTypes],
            tenantId,
            secretProtector.Protect(secret));
        if (!created.TryGetValue(out var subscription))
        {
            return Result.Failure<WebhookSubscriptionSecretResponse>(created.Errors);
        }

        await store.AddAsync(subscription, cancellationToken).ConfigureAwait(false);
        return Result.Success(new WebhookSubscriptionSecretResponse(ToResponse(subscription), secret));
    }

    /// <inheritdoc />
    public async Task<Result<WebhookSubscriptionResponse>> UpdateAsync(
        Guid id,
        UpdateWebhookSubscriptionRequest request,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(request);

        var subscription = await FindOwnAsync(id, cancellationToken).ConfigureAwait(false);
        if (subscription is null)
        {
            return Result.Failure<WebhookSubscriptionResponse>(NotFound(nameof(UpdateAsync)));
        }

        var eventTypes = request.EventTypes ?? [];
        var check = CheckDefinition(request.Url, eventTypes, nameof(UpdateAsync));
        if (check.IsFailure)
        {
            return Result.Failure<WebhookSubscriptionResponse>(check.Errors);
        }

        var target = await ValidateTargetAsync(request.Url, cancellationToken).ConfigureAwait(false);
        if (target.IsFailure)
        {
            return Result.Failure<WebhookSubscriptionResponse>(target.Errors);
        }

        var updated = subscription.Update(request.Url, request.Description, [.. eventTypes]);
        if (updated.IsFailure)
        {
            return Result.Failure<WebhookSubscriptionResponse>(updated.Errors);
        }

        await store.SaveAsync(subscription, cancellationToken).ConfigureAwait(false);
        return Result.Success(ToResponse(subscription));
    }

    /// <inheritdoc />
    public async Task<Result<WebhookSubscriptionSecretResponse>> RotateSecretAsync(Guid id, CancellationToken cancellationToken = default)
    {
        var subscription = await FindOwnAsync(id, cancellationToken).ConfigureAwait(false);
        if (subscription is null)
        {
            return Result.Failure<WebhookSubscriptionSecretResponse>(NotFound(nameof(RotateSecretAsync)));
        }

        var secret = WebhookSignature.GenerateSecret();
        subscription.RotateSecret(
            secretProtector.Protect(secret),
            UtcNow.AddHours(settings.Value.PreviousSecretGraceHours));

        await store.SaveAsync(subscription, cancellationToken).ConfigureAwait(false);
        return Result.Success(new WebhookSubscriptionSecretResponse(ToResponse(subscription), secret));
    }

    /// <inheritdoc />
    public Task<Result<WebhookSubscriptionResponse>> DisableAsync(Guid id, CancellationToken cancellationToken = default) =>
        ChangeAsync(id, subscription => subscription.Disable(UtcNow), nameof(DisableAsync), cancellationToken);

    /// <inheritdoc />
    public Task<Result<WebhookSubscriptionResponse>> EnableAsync(Guid id, CancellationToken cancellationToken = default) =>
        ChangeAsync(id, subscription => subscription.Enable(), nameof(EnableAsync), cancellationToken);

    /// <inheritdoc />
    public async Task<Result> DeleteAsync(Guid id, CancellationToken cancellationToken = default)
    {
        var subscription = await FindOwnAsync(id, cancellationToken).ConfigureAwait(false);
        if (subscription is null)
        {
            return Result.Failure(NotFound(nameof(DeleteAsync)));
        }

        var deleted = subscription.Delete();
        if (deleted.IsFailure)
        {
            return deleted;
        }

        await store.SaveAsync(subscription, cancellationToken).ConfigureAwait(false);
        return Result.Success();
    }

    private static WebhookSubscriptionResponse ToResponse(WebhookSubscription subscription) =>
        new(
            subscription.Id,
            subscription.Url,
            subscription.Description,
            subscription.GetEventTypes(),
            subscription.IsEnabled(),
            subscription.CreatedOn,
            subscription.LastDeliveredOn,
            subscription.LastFailedOn,
            subscription.LastFailure);

    private static Error NotFound(string source) =>
        Error.NotFoundError(WebhookErrorCodes.NotFound, "No webhook subscription with that id exists.", source);

    private async Task<Result<WebhookSubscriptionResponse>> ChangeAsync(
        Guid id,
        Action<WebhookSubscription> change,
        string source,
        CancellationToken cancellationToken)
    {
        var subscription = await FindOwnAsync(id, cancellationToken).ConfigureAwait(false);
        if (subscription is null)
        {
            return Result.Failure<WebhookSubscriptionResponse>(NotFound(source));
        }

        change(subscription);
        await store.SaveAsync(subscription, cancellationToken).ConfigureAwait(false);
        return Result.Success(ToResponse(subscription));
    }

    private async Task<WebhookSubscription?> FindOwnAsync(Guid id, CancellationToken cancellationToken)
    {
        var subscription = await store.FindAsync(id, tenantContext.TenantId, cancellationToken).ConfigureAwait(false);
        return subscription is { IsDeleted: false } ? subscription : null;
    }

    /// <summary>The URL parses as an absolute URI and every event type is the wildcard or registered.</summary>
    private Result CheckDefinition(string url, IReadOnlyList<string> eventTypes, string source)
    {
        List<Error> errors = [];

        if (string.IsNullOrWhiteSpace(url) || !Uri.TryCreate(url, UriKind.Absolute, out _))
        {
            errors.Add(Error.Validation(
                WebhookErrorCodes.UrlInvalid,
                "A webhook URL must be an absolute https or http URL.",
                source,
                nameof(url)));
        }

        var unknown = (eventTypes ?? [])
            .Where(eventType => !string.IsNullOrWhiteSpace(eventType)
                && !string.Equals(eventType.Trim(), WebhookSubscription.AllEventTypes, StringComparison.Ordinal)
                && !catalog.Contains(eventType.Trim()))
            .Distinct(StringComparer.Ordinal)
            .ToList();
        if (unknown.Count > 0)
        {
            errors.Add(Error.Validation(
                WebhookErrorCodes.EventTypeUnknown,
                $"Unknown webhook event type(s): {string.Join(", ", unknown)}.",
                source,
                nameof(eventTypes)));
        }

        return errors.Count == 0 ? Result.Success() : Result.Failure(errors);
    }

    private Task<Result> ValidateTargetAsync(string url, CancellationToken cancellationToken) =>
        targetValidator.ValidateAsync(new Uri(url, UriKind.Absolute), cancellationToken);
}
