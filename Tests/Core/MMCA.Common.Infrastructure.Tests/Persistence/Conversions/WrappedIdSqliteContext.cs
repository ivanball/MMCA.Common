/// <summary>
/// Shared scaffolding for the four wrapped-identifier contexts: the service provider each one needs
/// and the entity mapping they share.
/// <para>
/// The entities are mapped inline rather than through discovered
/// <c>EntityTypeConfiguration</c> classes on purpose. A discovered configuration is visible to every
/// OTHER test in this assembly that points an assembly provider at it, and an entity keyed by a
/// wrapper would then land in models whose context was never given the identifier registry.
/// </para>
/// </summary>
internal static class WrappedIdContextServices
{
    /// <summary>Builds the service provider an <c>ApplicationDbContext</c> subclass needs here.</summary>
    /// <param name="withRegistry">Whether to opt the context into strongly typed identifiers.</param>
    /// <returns>The service provider.</returns>
    public static IServiceProvider Create(bool withRegistry)
    {
        var services = new ServiceCollection();
        services.AddSingleton(new AuditSaveChangesInterceptor(TimeProvider.System));
        services.AddSingleton(_ => new DomainEventSaveChangesInterceptor(
            Mock.Of<IDomainEventDispatcher>(),
            NullLogger<DomainEventSaveChangesInterceptor>.Instance,
            Mock.Of<IOutboxSignal>()));
        services.AddSingleton<IEntityDataSourceRegistry>(new EmptyEntityDataSourceRegistry());

        if (withRegistry)
        {
            services.AddSingleton(new StronglyTypedIdRegistry(
                [typeof(OrderId), typeof(CustomerId), typeof(SpeakerId), typeof(LineId)]));
        }

        return services.BuildServiceProvider();
    }

    /// <summary>Maps the two wrapped-identifier entities.</summary>
    /// <param name="modelBuilder">The model builder.</param>
    public static void MapEntities(ModelBuilder modelBuilder)
    {
        ArgumentNullException.ThrowIfNull(modelBuilder);

        modelBuilder.Entity<WrappedOrder>(entity =>
        {
            entity.ToTable("WrappedOrders");
            entity.HasKey(e => e.Id);
            entity.Property(e => e.Id).ValueGeneratedOnAdd();
            entity.Ignore(e => e.DomainEvents);
        });

        modelBuilder.Entity<WrappedSpeaker>(entity =>
        {
            entity.ToTable("WrappedSpeakers");
            entity.HasKey(e => e.Id);
            entity.Property(e => e.Id).ValueGeneratedNever();
        });
    }

    /// <summary>An assembly provider that discovers nothing, so no configuration is swept in.</summary>
    internal sealed class NoAssemblies : IEntityConfigurationAssemblyProvider
    {
        public IReadOnlyList<Assembly> GetConfigurationAssemblies() => [];
    }
}
