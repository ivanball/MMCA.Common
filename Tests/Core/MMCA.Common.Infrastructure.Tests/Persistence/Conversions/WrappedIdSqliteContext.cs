/// <summary>An aggregate root keyed by a wrapper whose value the database generates.</summary>
[IdValueGenerated]
public sealed class WrappedOrder : AuditableAggregateRootEntity<OrderId>
{
    public string Code { get; set; } = string.Empty;

    public CustomerId CustomerId { get; set; }
}

/// <summary>An entity keyed by an application-assigned wrapper, holding an optional wrapper too.</summary>
public sealed class WrappedSpeaker : AuditableBaseEntity<SpeakerId>
{
    public string DisplayName { get; set; } = string.Empty;

    public LineId? SessionId { get; set; }
}

/// <summary>
/// A real SQLite database over entities keyed by strongly typed identifiers, built the way
/// <c>AuditTrailTestContext</c> is: the production <see cref="ApplicationDbContext"/> base, so the
/// pre-convention registration under test is the one production runs, with the entity mapping
/// declared inline rather than discovered.
/// </summary>
public sealed class WrappedIdSqliteContext : ApplicationDbContext
{
    private WrappedIdSqliteContext(DbContextOptions<WrappedIdSqliteContext> options, IServiceProvider serviceProvider)
        : base(options, serviceProvider, new WrappedIdContextServices.NoAssemblies(), TestPhysicalDataSources.Sqlite())
    {
    }

    public DbSet<WrappedOrder> Orders => Set<WrappedOrder>();

    public DbSet<WrappedSpeaker> Speakers => Set<WrappedSpeaker>();

    internal override bool SupportsOutbox => false;

    /// <summary>Creates the context over a fresh in-memory database.</summary>
    /// <returns>An open context whose schema has been created.</returns>
    public static WrappedIdSqliteContext Create()
    {
        var options = new DbContextOptionsBuilder<WrappedIdSqliteContext>()
            .UseSqlite("DataSource=:memory:")
            .Options;

        var context = new WrappedIdSqliteContext(options, WrappedIdContextServices.Create(withRegistry: true));
        context.Database.OpenConnection();
        context.Database.EnsureCreated();
        return context;
    }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
        => WrappedIdContextServices.MapEntities(modelBuilder);
}

